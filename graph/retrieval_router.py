import json
from typing import Dict, Any


# ============================================================
# RETRIEVAL ROUTER
# ============================================================

class RetrievalRouter:

    """
    Deterministic router for the Graph RAG retrieval layer.

    The router receives the structured output generated by
    Query Understanding and decides whether the query should
    use:

        - Neo4j
        - LightRAG
        - Hybrid retrieval
    """

    # --------------------------------------------------------
    # MAIN ROUTING METHOD
    # --------------------------------------------------------

    def route(
        self,
        query_understanding: Dict[str, Any]
    ) -> Dict[str, Any]:

        intent = query_understanding.get("intent", "")

        entities = query_understanding.get(
            "entities",
            {}
        )

        filters = query_understanding.get(
            "filters",
            {}
        )

        test_case_ids = entities.get(
            "test_case_ids",
            []
        )

        execution_ids = entities.get(
            "execution_ids",
            []
        )

        defect_ids = entities.get(
            "defect_ids",
            []
        )

        # ----------------------------------------------------
        # RULE 1
        # Specific defect ID
        # ----------------------------------------------------

        if defect_ids:

            return self._build_route(
                route="neo4j",
                reason="Specific defect ID requires authoritative structured lookup.",
                retrievers=["neo4j"],
                query_type="specific_entity_lookup"
            )

        # ----------------------------------------------------
        # RULE 2
        # Specific execution ID
        # ----------------------------------------------------

        if execution_ids:

            # Failure analysis benefits from graph context
            if intent == "failure_analysis":

                return self._build_route(
                    route="hybrid",
                    reason="Specific execution failure requires graph context and semantic evidence.",
                    retrievers=[
                        "neo4j",
                        "lightrag"
                    ],
                    query_type="execution_failure_analysis"
                )

            return self._build_route(
                route="neo4j",
                reason="Specific execution ID requires authoritative structured lookup.",
                retrievers=["neo4j"],
                query_type="specific_entity_lookup"
            )

        # ----------------------------------------------------
        # RULE 3
        # TestCase + execution/defect analysis
        # ----------------------------------------------------

        if test_case_ids:

            if intent in [
                "testcase_execution_analysis",
                "failure_analysis",
                "defect_analysis",
            ]:

                return self._build_route(
                    route="hybrid",
                    reason="Test case analysis benefits from exact graph relationships and semantic retrieval.",
                    retrievers=[
                        "neo4j",
                        "lightrag"
                    ],
                    query_type="testcase_analysis"
                )

            return self._build_route(
                route="neo4j",
                reason="Specific test case requires authoritative structured lookup.",
                retrievers=["neo4j"],
                query_type="specific_entity_lookup"
            )

        # ----------------------------------------------------
        # RULE 4
        # Structured filters
        # ----------------------------------------------------

        if filters:

            return self._build_route(
                route="neo4j",
                reason="Structured filters require exact property-based retrieval.",
                retrievers=["neo4j"],
                query_type="structured_filter"
            )

        # ----------------------------------------------------
        # RULE 5
        # Semantic search
        # ----------------------------------------------------

        if intent in [
            "semantic_search",
            "screenshot_lookup",
        ]:

            return self._build_route(
                route="lightrag",
                reason="Semantic or exploratory query is better suited to LightRAG retrieval.",
                retrievers=["lightrag"],
                query_type="semantic_search"
            )

        # ----------------------------------------------------
        # RULE 6
        # Failure analysis without specific ID
        # ----------------------------------------------------

        if intent == "failure_analysis":

            return self._build_route(
                route="hybrid",
                reason="Failure analysis requires both structured relationships and semantic evidence.",
                retrievers=[
                    "neo4j",
                    "lightrag"
                ],
                query_type="failure_analysis"
            )

        # ----------------------------------------------------
        # RULE 7
        # Defect analysis
        # ----------------------------------------------------

        if intent == "defect_analysis":

            return self._build_route(
                route="hybrid",
                reason="Defect analysis benefits from structured defect relationships and semantic context.",
                retrievers=[
                    "neo4j",
                    "lightrag"
                ],
                query_type="defect_analysis"
            )

        # ----------------------------------------------------
        # RULE 8
        # General test analysis
        # ----------------------------------------------------

        if intent == "general_test_analysis":

            return self._build_route(
                route="hybrid",
                reason="General test analysis may require both structured and semantic evidence.",
                retrievers=[
                    "neo4j",
                    "lightrag"
                ],
                query_type="general_analysis"
            )

        # ----------------------------------------------------
        # DEFAULT
        # ----------------------------------------------------

        return self._build_route(
            route="lightrag",
            reason="No strong structured signal was detected; use semantic retrieval.",
            retrievers=["lightrag"],
            query_type="default_semantic_search"
        )

    # --------------------------------------------------------
    # ROUTE RESULT BUILDER
    # --------------------------------------------------------

    def _build_route(
        self,
        route: str,
        reason: str,
        retrievers: list,
        query_type: str
    ) -> Dict[str, Any]:

        return {
            "route": route,
            "retrievers": retrievers,
            "query_type": query_type,
            "reason": reason
        }


